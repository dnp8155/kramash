// Builds supabase/functions/_shared/appKnowledge.ts: the help the AI assistant looks things up in (the FAQ and the
// feature guide on the Help page), as plain text pieces. The Edge Function can't import from src/, so this copies it.
// Run again after the FAQ or the guide changes:  npm run build:assistant
// Prices and plan details are left out on purpose (they change); the assistant sends people to the Your Plan page.
import { createServer } from "vite";
import fs from "fs";
import path from "path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
// The guide's file also imports screen components that look for a browser; this stand-in is enough for them to load.
globalThis.window ??= globalThis;
globalThis.document ??= { documentElement: { classList: { add() {}, remove() {} }, style: {} }, addEventListener() {}, createElement: () => ({ style: {} }), querySelector: () => null };
globalThis.localStorage ??= { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.matchMedia ??= () => ({ matches: false, addEventListener() {}, removeEventListener() {} });

// Vite loads the two source files the same way the app does (the @ shortcut, JSX), without starting a web server.
const server = await createServer({ root, logLevel: "error", appType: "custom", server: { middlewareMode: true, hmr: false, watch: null } });
let faqContent, plainAnswer, CATEGORIES;
try {
  ({ faqContent, plainAnswer } = await server.ssrLoadModule("/src/constants/faqContent.js"));
  ({ CATEGORIES } = await server.ssrLoadModule("/src/components/help/FeatureGuide.jsx"));
} finally {
  await server.close();
}

const chunks = [];
for (const f of faqContent) {
  if (f.category === "plans") continue; // prices and limits change: not copied
  chunks.push({ title: f.q, text: plainAnswer(f.a) });
}
for (const c of CATEGORIES) {
  for (const f of c.features) {
    chunks.push({ title: `${c.label}: ${f.title}`, text: `${f.desc} Steps: ${(f.steps || []).map((s, i) => `${i + 1}. ${s}`).join(" ")}` });
  }
}
const clean = (s) => String(s).replace(/\s+/g, " ").trim();
const body = chunks.map((c) => ({ title: clean(c.title), text: clean(c.text) }));
fs.writeFileSync(path.join(root, "supabase/functions/_shared/appKnowledge.ts"),
`// GENERATED by scripts/buildAssistantKnowledge.mjs (npm run build:assistant). Do not edit by hand.
// Help the AI assistant looks things up in: the FAQ and the feature guide.
export const APP_KNOWLEDGE: { title: string; text: string }[] = ${JSON.stringify(body, null, 1)};
`);
console.log(`appKnowledge.ts: ${body.length} pieces, ${body.reduce((n, c) => n + c.text.length, 0)} characters`);
